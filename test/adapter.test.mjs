import assert from 'node:assert/strict';
import { test } from 'node:test';
import { setTimeout as delay } from 'node:timers/promises';
import { EventAdapter } from '../src/event-adapter.mjs';

test('scopes, deduplicates and maps tool, stream and terminal events', async () => {
  const emitted = [];
  let now = 0;
  const adapter = new EventAdapter(snapshot => emitted.push(snapshot), { linger: 15, clock: () => now });
  adapter.reset('thread');
  const turn = { id: 'turn', status: 'inProgress' };
  const event = (method, fields) => adapter.notify(method, { threadId: 'thread', turnId: 'turn', ...fields });
  event('turn/started', { threadId: 'another-thread', turn });
  assert.equal(adapter.snapshot.state, 'idle');
  event('turn/started', { turn });
  assert.equal(adapter.snapshot.state, 'working');
  const command = { id: 'cmd', type: 'commandExecution', cwd: 'PRIVATE_PATH', command: 'SECRET_COMMAND' };
  const file = { id: 'file', type: 'fileChange', changes: [{ path: 'PRIVATE_PATH', diff: 'PRIVATE_DIFF' }] };
  event('item/started', { item: command });
  event('item/started', { item: command });
  event('item/started', { item: file });
  assert.equal(adapter.snapshot.counts.command, 1);
  assert.equal(adapter.snapshot.activeTools, 2);
  assert.equal(adapter.snapshot.activity, 'file');
  event('item/completed', { item: { ...command, status: 'failed' } });
  assert.equal(adapter.snapshot.state, 'tool_running');
  assert.equal(adapter.snapshot.activityResult, 'failed');
  event('item/completed', { item: { ...file, status: 'completed' } });
  event('item/started', { item: file });
  assert.equal(adapter.snapshot.activeTools, 0);
  assert.equal(adapter.snapshot.counts.file, 1);
  const delta = { itemId: 'message', delta: 'PRIVATE_TEXT' };
  event('item/agentMessage/delta', delta);
  const pulse = adapter.snapshot.pulse;
  assert.equal(adapter.snapshot.state, 'streaming');
  event('item/agentMessage/delta', delta);
  assert.equal(adapter.snapshot.pulse, pulse);
  now += 100;
  event('item/agentMessage/delta', delta);
  assert.equal(adapter.snapshot.pulse, pulse + 1);
  event('item/completed', { item: { id: 'message', type: 'agentMessage' } });
  assert.equal(adapter.snapshot.state, 'working');
  event('error', { willRetry: true, error: { message: 'PRIVATE_ERROR' } });
  assert.equal(adapter.snapshot.state, 'working');
  event('turn/completed', { turn: { ...turn, status: 'completed' } });
  assert.equal(adapter.snapshot.state, 'completed');
  event('turn/started', { turn });
  event('turn/completed', { turn: { ...turn, status: 'completed' } });
  assert.equal(adapter.snapshot.state, 'completed');
  await delay(30);
  assert.equal(adapter.snapshot.state, 'idle');
  assert.equal(adapter.snapshot.outcome, 'completed');
  assert.doesNotMatch(JSON.stringify(emitted), /PRIVATE_|SECRET_|turnId|threadId/);
});

test('approval priority, multiple requests, fatal error and interrupted turn', () => {
  const adapter = new EventAdapter(() => {});
  adapter.reset('thread');
  adapter.startTurn('turn');
  adapter.approval(1, 'command', 'turn', 'opaque-1');
  adapter.approval('1', 'file', 'turn', 'opaque-2');
  adapter.approval(1, 'command', 'turn', 'duplicate');
  assert.equal(adapter.snapshot.state, 'approval_required');
  assert.deepEqual(adapter.snapshot.approvals, [
    { kind: 'command' }, { kind: 'file' },
  ]);
  adapter.notify('serverRequest/resolved', { threadId: 'thread', requestId: 1 });
  adapter.approval(1, 'command', 'turn', 'stale');
  assert.equal(adapter.snapshot.approvals.length, 1);
  adapter.notify('error', { threadId: 'thread', turnId: 'turn', willRetry: false });
  assert.equal(adapter.snapshot.state, 'failed');
  assert.equal(adapter.snapshot.active, true);
  adapter.finishTurn('turn', 'failed');
  assert.equal(adapter.snapshot.state, 'failed');
  assert.equal(adapter.snapshot.active, false);
  assert.equal(adapter.snapshot.approvals.length, 0);
  adapter.startTurn('next');
  adapter.finishTurn('next', 'interrupted');
  assert.equal(adapter.snapshot.state, 'interrupted');
  assert.equal(adapter.snapshot.outcome, 'interrupted');
  adapter.reset(null);
});
